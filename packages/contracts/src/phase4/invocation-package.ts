/**
 * Versioned Invocation Package contract (architecture.md §9.3): the complete,
 * frozen input handed to the modeling Skill for one Run attempt. The package is
 * generated by the Runner from the frozen `RunInputSnapshot` and the Input
 * Adapter provenance; the Agent never sees a client-supplied snapshot. `revisionFacts`
 * and `modelingFeedback` reuse the canonical `@swpanel/domain` memory types.
 */
export const INVOCATION_PACKAGE_CONTRACT_VERSION = 1 as const;

export interface InvocationPackageSkill {
  name: string;
  /** Approved SHA-256 of the modeling Skill definition. */
  sha256: string;
}

export interface InvocationPackageInput {
  /** Stable reference to the original drawing file artifact. */
  originalArtifactId: string;
  /** Workspace path of the adapter-derived Skill input image. */
  imagePath: string;
  /** SHA-256 of the derived image bytes. */
  imageSha256: string;
}

export interface InvocationPackageMemory {
  revisionFacts: readonly RevisionFact[];
  modelingFeedback: readonly ModelingFeedback[];
}

export interface InvocationPackageWorkspace {
  root: string;
  output: string;
}

/**
 * MVP defaults to background execution. Visible-live execution is a runtime
 * option for approved diagnostic or review workflows.
 */
export const INVOCATION_EXECUTION_VISIBILITIES = ["background", "visible"] as const;
export type InvocationExecutionVisibility = (typeof INVOCATION_EXECUTION_VISIBILITIES)[number];

export interface InvocationPackageExecution {
  visibility: InvocationExecutionVisibility;
  /** MP4 recording becomes required only when true. */
  recordMp4: boolean;
}

export interface InvocationPackage {
  contractVersion: typeof INVOCATION_PACKAGE_CONTRACT_VERSION;
  runId: string;
  skill: InvocationPackageSkill;
  input: InvocationPackageInput;
  memory: InvocationPackageMemory;
  workspace: InvocationPackageWorkspace;
  execution: InvocationPackageExecution;
}

