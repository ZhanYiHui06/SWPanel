const REVISION_FACT_SOURCE_SET: ReadonlySet<string> = new Set(REVISION_FACT_SOURCES);
const MODELING_FEEDBACK_SOURCE_SET: ReadonlySet<string> = new Set(MODELING_FEEDBACK_SOURCES);

function assertRevisionFact(fact: unknown): RevisionFact {
  if (!isRecord(fact)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "each revision fact must be an object");
  }
  assertNoUnknownKeys(
    fact,
    ["id", "revisionId", "field", "value", "unit", "source", "sourceRunId", "createdAt", "createdBy"],
    "revision fact"
  );
  const id = assertNonEmptyString(fact, "id", "revision fact");
  const revisionId = assertNonEmptyString(fact, "revisionId", "revision fact");
  const field = assertNonEmptyString(fact, "field", "revision fact");
  const value = assertNonEmptyString(fact, "value", "revision fact");
  const unit = assertOptionalNonEmptyString(fact, "unit", "revision fact");
  if (typeof fact.source !== "string" || !REVISION_FACT_SOURCE_SET.has(fact.source)) {
    throw new Phase4ContractError(
      "INVALID_CONTRACT",
      "revision fact.source must be a revision-fact source"
    );
  }
  const sourceRunId = assertOptionalNonEmptyString(fact, "sourceRunId", "revision fact");
  const createdAt = assertIsoTimestamp(fact, "createdAt", "revision fact");
  const createdBy = assertOptionalNonEmptyString(fact, "createdBy", "revision fact");
  return {
    id,
    revisionId,
    field,
    value,
    ...(unit === undefined ? {} : { unit }),
    source: fact.source as RevisionFact["source"],
    ...(sourceRunId === undefined ? {} : { sourceRunId }),
    createdAt,
    ...(createdBy === undefined ? {} : { createdBy })
  };
}

function assertModelingFeedback(feedback: unknown): ModelingFeedback {
  if (!isRecord(feedback)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "each modeling feedback must be an object");
  }
  assertNoUnknownKeys(
    feedback,
    ["id", "revisionId", "modelId", "reviewId", "content", "source", "createdAt"],
    "modeling feedback"
  );
  const id = assertNonEmptyString(feedback, "id", "modeling feedback");
  const revisionId = assertNonEmptyString(feedback, "revisionId", "modeling feedback");
  const modelId = assertOptionalNonEmptyString(feedback, "modelId", "modeling feedback");
  const reviewId = assertOptionalNonEmptyString(feedback, "reviewId", "modeling feedback");
  const content = assertNonEmptyString(feedback, "content", "modeling feedback");
  if (typeof feedback.source !== "string" || !MODELING_FEEDBACK_SOURCE_SET.has(feedback.source)) {
    throw new Phase4ContractError(
      "INVALID_CONTRACT",
      "modeling feedback.source must be a modeling-feedback source"
    );
  }
  const createdAt = assertIsoTimestamp(feedback, "createdAt", "modeling feedback");
  return {
    id,
    revisionId,
    ...(modelId === undefined ? {} : { modelId }),
    ...(reviewId === undefined ? {} : { reviewId }),
    content,
    source: feedback.source as ModelingFeedback["source"],
    createdAt
  };
}

/**
 * Strictly validates a serialized Invocation Package. Throws
 * {@link Phase4ContractError} on the first violation: contract version mismatch,
 * unknown fields, illegal enums, malformed hashes or memory items.
 */
export function validateInvocationPackage(value: unknown): InvocationPackage {
  if (!isRecord(value)) {
    throw new Phase4ContractError(
      "INVALID_CONTRACT",
      "Invocation Package must be a JSON object"
    );
  }
  assertNoUnknownKeys(
    value,
    ["contractVersion", "runId", "skill", "input", "memory", "workspace", "execution"],
    "Invocation Package"
  );
  if (value.contractVersion !== INVOCATION_PACKAGE_CONTRACT_VERSION) {
    throw new Phase4ContractError(
      "VERSION_MISMATCH",
      `Expected contractVersion ${INVOCATION_PACKAGE_CONTRACT_VERSION}, got ${JSON.stringify(value.contractVersion)}`
    );
  }
  const runId = assertNonEmptyString(value, "runId", "Invocation Package");

  const skill = value.skill;
  if (!isRecord(skill)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "skill must be an object");
  }
  assertNoUnknownKeys(skill, ["name", "sha256"], "skill");
  const skillName = assertNonEmptyString(skill, "name", "skill");
  if (!isSha256Hex(skill.sha256)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "skill.sha256 must be a 64-char hex digest");
  }

  const input = value.input;
  if (!isRecord(input)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "input must be an object");
  }
  assertNoUnknownKeys(input, ["originalArtifactId", "imagePath", "imageSha256"], "input");
  const originalArtifactId = assertNonEmptyString(input, "originalArtifactId", "input");
  const imagePath = assertNonEmptyString(input, "imagePath", "input");
  if (!isSha256Hex(input.imageSha256)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "input.imageSha256 must be a 64-char hex digest");
  }

  const memory = value.memory;
  if (!isRecord(memory)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "memory must be an object");
  }
  assertNoUnknownKeys(memory, ["revisionFacts", "modelingFeedback"], "memory");
  const revisionFactsValue = memory.revisionFacts;
  if (!Array.isArray(revisionFactsValue)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "memory.revisionFacts must be an array");
  }
  const revisionFacts: RevisionFact[] = [];
  for (const fact of revisionFactsValue) {
    revisionFacts.push(assertRevisionFact(fact));
  }
  const modelingFeedbackValue = memory.modelingFeedback;
  if (!Array.isArray(modelingFeedbackValue)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "memory.modelingFeedback must be an array");
  }
  const modelingFeedback: ModelingFeedback[] = [];
  for (const feedback of modelingFeedbackValue) {
    modelingFeedback.push(assertModelingFeedback(feedback));
  }

  const workspace = value.workspace;
  if (!isRecord(workspace)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "workspace must be an object");
  }
  assertNoUnknownKeys(workspace, ["root", "output"], "workspace");
  const workspaceRoot = assertNonEmptyString(workspace, "root", "workspace");
  const output = assertNonEmptyString(workspace, "output", "workspace");

  const execution = value.execution;
  if (!isRecord(execution)) {
    throw new Phase4ContractError("INVALID_CONTRACT", "execution must be an object");
  }
  assertNoUnknownKeys(execution, ["visibility", "recordMp4"], "execution");
  if (
    typeof execution.visibility !== "string" ||
    !INVOCATION_EXECUTION_VISIBILITIES.includes(execution.visibility as never)
  ) {
    throw new Phase4ContractError(
      "INVALID_CONTRACT",
      "execution.visibility must be one of background, visible"
    );
  }
  if (typeof execution.recordMp4 !== "boolean") {
    throw new Phase4ContractError("INVALID_CONTRACT", "execution.recordMp4 must be a boolean");
  }

  return {
    contractVersion: INVOCATION_PACKAGE_CONTRACT_VERSION,
    runId,
    skill: { name: skillName, sha256: skill.sha256 },
    input: { originalArtifactId, imagePath, imageSha256: input.imageSha256 },
    memory: {
      revisionFacts,
      modelingFeedback
    },
    workspace: { root: workspaceRoot, output },
    execution: {
      visibility: execution.visibility as InvocationExecutionVisibility,
      recordMp4: execution.recordMp4
    }
  };
}
